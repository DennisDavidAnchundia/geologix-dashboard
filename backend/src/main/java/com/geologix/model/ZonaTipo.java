/**
 * Tipos de zona geográfica para las geofences.
 */
public enum ZonaTipo {
    /** Almacén o centro de distribución. */
    ALMACEN,
    /** Zona de reparto autorizada. */
    ZONA_REPARTO,
    /** Zona restringida o prohibida. */
    RESTRINGIDA,
    /** Zona de cobertura general. */
    COBERTURA
}
